/// Роль строки в чеке.
enum ReceiptLineKind {
  /// Позиция меню.
  item,

  /// Итоговая сумма чека.
  total,

  /// Промежуточная сумма до сервисного сбора.
  subtotal,

  /// Сервисный сбор или чаевые.
  service,

  /// Скидка.
  discount,

  /// Служебная строка: реквизиты, дата, благодарности.
  noise,
}
